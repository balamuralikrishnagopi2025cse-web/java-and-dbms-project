    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        
String url = "jdbc:mysql://localhost/library";
String user = "root";
String pwd = "MyNewPass@123";

String query = "insert into books values(?,?,?,?,?)";

String id = t1.getText();
String category = t2.getText();
String name = t3.getText();
String author = t4.getText();
int copies = Integer.parseInt(t5.getText());

String checkquery = "update books set copies=copies+" + copies
        + " where name='" + name + "' and category='" + category
        + "' and author='" + author + "'";

try {
    Connection conn = DriverManager.getConnection(url, user, pwd);
    Statement stmt = conn.createStatement();

    int rows = stmt.executeUpdate(checkquery);

    if (rows > 0) {
        JOptionPane.showMessageDialog(this, "One record added successfully");
    } else {
        PreparedStatement stm = conn.prepareCall(query);

        stm.setString(1, id);
        stm.setString(2, category);
        stm.setString(3, name);
        stm.setString(4, author);
        stm.setInt(5, copies);

        stm.execute();

        JOptionPane.showMessageDialog(this, "One record added successfully");
    }

    t1.setText(null);
    t2.setText(null);
    t3.setText(null);
    t4.setText(null);
    t5.setText(null);

} catch (Exception e) {
    JOptionPane.showMessageDialog(this, e);
}

    }//GEN-LAST:event_jButton1ActionPerformed

